export const DEFAULT_THEME_ID = 'floral'

export function getTheme(id: string): ThemePreset {
  return THEMES.find((t) => t.id === id) ?? THEMES[0]
}

export function getFontPair(id: string): FontPair {
  return FONT_PAIRS.find((f) => f.id === id) ?? FONT_PAIRS[0]
}

export function customFromTheme(t: ThemePreset): Customization {
  return {
    themeId: t.id,
    primary: t.primary,
    secondary: t.secondary,
    fontPairId: t.fontPairId,
    background: t.bg,
    decor: t.decor,
    animation: t.animation,
  }
}

